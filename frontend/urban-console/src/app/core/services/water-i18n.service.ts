@Injectable({ providedIn: 'root' })
export class WaterI18nService {
  readonly lang = signal<WaterLang>(this.saved());

  private saved(): WaterLang {
    try {
      return localStorage.getItem(LANG_KEY) === 'te' ? 'te' : 'en';
    } catch {
      return 'en';
    }
  }

  toggle(): void {
    const next: WaterLang = this.lang() === 'en' ? 'te' : 'en';
    this.lang.set(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      /* storage blocked: the choice lasts for this visit */
    }
  }

  t(key: string): string {
    return DICT[this.lang()][key] ?? DICT.en[key] ?? key;
  }

  /** Both languages, used on bills, receipts and notices which are always bilingual. */
  both(key: string): string {
    return `${DICT.te[key] ?? key} / ${DICT.en[key] ?? key}`;
  }

  te(key: string): string {
    return DICT.te[key] ?? key;
  }

  en(key: string): string {
    return DICT.en[key] ?? key;
  }
}
