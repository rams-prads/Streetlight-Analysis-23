@Injectable({ providedIn: 'root' })
export class PtxI18nService {
  readonly lang = signal<PtxLang>(this.saved());

  private saved(): PtxLang {
    try {
      return localStorage.getItem(LANG_KEY) === 'te' ? 'te' : 'en';
    } catch {
      return 'en';
    }
  }

  toggle(): void {
    const next: PtxLang = this.lang() === 'en' ? 'te' : 'en';
    this.lang.set(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      /* storage blocked: the choice lasts for this visit */
    }
  }

  t(key: string): string {
    return DICT[this.lang()][key] ?? DICT.en[key] ?? key;
  }

  /** Both languages, used on receipts, bills, notices and certificates, which are always bilingual (PT-32). */
  both(key: string): string {
    return `${DICT.te[key] ?? key} / ${DICT.en[key] ?? key}`;
  }

  te(key: string): string {
    return DICT.te[key] ?? key;
  }

  en(key: string): string {
    return DICT.en[key] ?? key;
  }

  /** Code list entry in the chosen language. */
  name(item: { nameEn: string; nameTe: string } | undefined | null, fallback = ''): string {
    if (!item) return fallback;
    return this.lang() === 'te' ? item.nameTe || item.nameEn : item.nameEn;
  }
}
