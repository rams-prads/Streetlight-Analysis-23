def _mrv(scale: float) -> dict:
    base = {"RESIDENTIAL": {"RCC": 1.50, "TILED": 1.00, "ASBESTOS": 0.80, "KUTCHA": 0.40},
            "COMMERCIAL": {"RCC": 4.00, "TILED": 2.50, "ASBESTOS": 2.00, "KUTCHA": 1.00},
            "INSTITUTIONAL": {"RCC": 1.20, "TILED": 0.90, "ASBESTOS": 0.70, "KUTCHA": 0.35},
            "INDUSTRIAL": {"RCC": 2.00, "TILED": 1.40, "ASBESTOS": 1.20, "KUTCHA": 0.60}}
    return {use: {c: round(v * scale, 2) for c, v in by_c.items()} for use, by_c in base.items()}


