async def _seed_reference(db: AsyncSession) -> bool:
    if await db.scalar(select(PtxCode.id).where(PtxCode.tenant_id == TENANT)):
        return False
    from app.api.v1.ptx.common import DEFAULT_SETTINGS
    start = datetime.date(datetime.date.today().year - 2, 4, 1)  # covers the seeded history
    for list_name, code, en, te, extra in CODES:
        db.add(PtxCode(tenant_id=TENANT, list_name=list_name, code=code, name_en=en, name_te=te, extra_json=json.dumps(extra)))
    for key, value in DEFAULT_SETTINGS.items():
        db.add(PtxSetting(tenant_id=TENANT, key=key, value_json=json.dumps(value), effective_from=start, created_by=SEED_ACTOR,
                          reason="Initial configuration - placeholder values pending GWMC confirmation (SRS Appendix A)"))
    db.add(PtxRateTable(tenant_id=TENANT, version=1, effective_from=start, rules_json=json.dumps(RULES), status="APPROVED", order_reference=PLACEHOLDER,
                        reason="Initial rate table", requested_by=SEED_ACTOR, approved_by=SEED_ACTOR, approved_at=utcnow()))
    await db.commit()
    return True


