async def _seed_demo_accounts(db: AsyncSession) -> None:
    for username, name, role, ward, zone in DEMO_ACCOUNTS:
        if await db.scalar(select(User.id).where(User.username == username)) is None:
            db.add(User(tenant_id=TENANT, username=username, email=username, password_hash=hash_password("Demo@123"), full_name=name, role=role,
                        assigned_modules="PTX,GRV,DMS", assigned_ward=ward, assigned_zone=zone))
    # the shared counter, Commissioner and Meeseva accounts also work in Property Tax
    for user in (await db.execute(select(User).where(User.username.in_(SHARED_ACCOUNTS)))).scalars().all():
        modules = [m for m in (user.assigned_modules or "").split(",") if m]
        if "PTX" not in modules:
            user.assigned_modules = ",".join(modules + ["PTX"])
    await db.commit()
    for username, old_no, mobile in DEMO_CITIZEN_LINKS:
        prop = await db.scalar(select(PtxProperty).where(PtxProperty.tenant_id == TENANT, PtxProperty.old_assessment_no == old_no))
        if prop is None or await db.scalar(select(User.id).where(User.username == username)) is None:
            continue
        if await db.scalar(select(PtxCitizenLink.id).where(PtxCitizenLink.tenant_id == TENANT, PtxCitizenLink.username == username,
                                                            PtxCitizenLink.property_id == prop.id)) is None:
            db.add(PtxCitizenLink(tenant_id=TENANT, username=username, property_id=prop.id, mobile_number=mobile))
    await db.commit()


async def seed_ptx_data(db: AsyncSession) -> None:
    if settings.ENVIRONMENT == "development":
        try:
            await _seed_reference_then_demo(db)
        finally:
            await _seed_demo_accounts(db)
        return
    await _seed_reference_then_demo(db)


async def _seed_reference_then_demo(db: AsyncSession) -> None:
    created = await _seed_reference(db)
    if not created:
        done = await db.scalar(select(PtxCounter.value).where(PtxCounter.tenant_id == TENANT, PtxCounter.name == "seed_done"))
        if settings.ENVIRONMENT == "development" and not done:
            logger.warning("Property tax demo data looks incomplete (an earlier start-up stopped part way). Recreate the database to reload it.")
        return
    logger.info("Property tax reference data (code lists, settings, placeholder rate table) seeded.")
    if settings.ENVIRONMENT == "development":
        await _seed_demo(db)
        logger.info("Property tax demo data seeded (development only).")
